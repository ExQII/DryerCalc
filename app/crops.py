"""Культуры: профиль каждой (свойства зерна, кондиции, режимы) и стартовая модель сушки для неё.

Зачем профиль. Сушилка одна, а зерно разное: у каждой культуры своя насыпная плотность (отсюда т/ч выгрузки и
вместимость шахты в тоннах), своя влажность хранения, свои пределы нагрева и свой съём влаги за пропуск. У каждой
культуры в программе свой журнал, своя модель, свои партии и своя поправка влагомера (storage.CROP_KEYS) — культура
переключается в разделе «Культура».

Стартовая модель культуры (пока по ней нет своего журнала) — пересчёт модели ЭТОЙ сушилки, откалиброванной на
кукурузе, по двум правилам:

1. Равная равновесная влажность воздуха. Насколько «охотно» зерно отдаёт влагу, определяет не процент влажности,
   а равновесная относительная влажность воздуха над ним (ERH). Рапс при 10 % и кукуруза при 15 % держат над собой
   воздух одной влажности (≈ 74 % при 25 °C) — и сохнут с одной «движущей силой». Поэтому влажность культуры
   переводится в «влажность кукурузы с той же ERH» линейно по двум точкам: ERH кукурузы при 8 и при 15 % (25 °C).
   Изотермы: кукуруза, пшеница, соя — модифицированное уравнение Хендерсона, константы ASAE D245 (кукуруза
   8,6541·10⁻⁵ / 1,8634 / 49,810; пшеница твёрдозёрная 2,3007·10⁻⁵ / 2,2857 / 55,815; соя 30,5327·10⁻⁵ / 1,2164 /
   134,136); рапс — модифицированное уравнение Хэлси, десорбция, Sun & Byrne, 1998 (2,8989 / −1,4596·10⁻² / 1,5454);
   подсолнечник — по опорным точкам масличного подсолнечника: 8 % ↔ 65 % и 9 % ↔ 75 % RH (GRDC Stored Grain,
   «Safe storage of sunflower seed», 2015). Отсюда EQV: влажность культуры, равноценная кукурузе при 8 и при 22 %.
2. Расход влаги R (т воды/ч) — свойство сушилки: при той же T агента и той же «движущей силе» шахта испаряет
   столько же воды, на какой бы культуре ни работала (её предел — тепло воздуха, а не зерно). Поправка — только
   там, где её дают нормы: по Инструкции № 9-3-82 производительность шахтной сушилки на кукурузе — 0,6 от пшеницы
   при том же съёме (коэффициент K_к), то есть пшеница сохнет примерно в 1,6 раза быстрее кукурузы. Для рапса,
   подсолнечника и сои нормативной цифры «при равной температуре» нет — множитель 1,0.

Это оценка, а не калибровка: ±30 % по скорости сушки (rate_sigma = 0,25 — допуски в планах широкие). Первые же
12 строк журнала культуры калибруют модель по факту, и дальше она ничем не отличается от модели кукурузы.

Пределы нагрева и съём за пропуск — Инструкция по сушке продовольственного, кормового зерна, маслосемян и
эксплуатации зерносушилок № 9-3-82, табл. 1 (шахтные прямоточные сушилки) и п. 6.3: пшеница с хорошей клейковиной
до 20 % — зерно 50 °C, агент 140 °C; подсолнечник — 55 / 115 °C; соя до 19 % — 30 / 60 °C, съём не более 3 п.п.;
кукуруза — съём 4,5–5,5 п.п.; остальные культуры — 6 п.п. Рапса в табл. 1 нет — взяты обычные для товарных
маслосемян 45 / 80 °C. Пределы — стартовые: для семенного зерна, сильной пшеницы и сырого зерна они ниже,
поправьте в «Настройках сушилки» по своей технологической карте.

Насыпная плотность — НТП-АПК 1.10.10.001-02, прил. Д: пшеница 750, кукуруза 700, соя 720, подсолнечник 350 кг/м³;
рапс — 650 (в приложении только сурепица, 410–660). Q(D) и вместимость шахты — объёмные, поэтому в тоннах они
пересчитываются отношением плотностей к кукурузе.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Dict, List, Optional, Tuple

from . import model as mdl

DEFAULT = "corn"


@dataclass(frozen=True)
class Crop:
    key: str
    name: str            # «Кукуруза»
    gen: str             # «кукурузы» (кого? чего?)
    density: float       # насыпная плотность, кг/м³
    eqv8: float          # влажность, равноценная кукурузе при 8 % (та же ERH), %
    eqv22: float         # … при 22 %
    k_speed: float       # скорость сушки относительно кукурузы при равных T и «движущей силе»
    w_store: float       # влажность хранения — цель сушки, %
    w0: float            # типичная влажность с поля (для полей ввода), %
    soft: float          # желаемый съём за проход, п.п.
    hard: float          # допустимый съём за проход, п.п.
    t_agent_max: float   # предел T агента (блоков), °C
    t_grain_max: float   # предел нагрева зерна, °C
    t_proc: float        # обычная T блоков (для полей ввода), °C
    note: str            # одна строка о главном при сушке культуры


CROPS: Tuple[Crop, ...] = (
    Crop("corn", "Кукуруза", "кукурузы", 700.0, 8.0, 22.0, 1.0, 14.0, 30.0, 6.0, 10.0, 75.0, 75.0, 60.0,
         "Сырая — в несколько проходов; по инструкции съём 4,5–5,5 п.п. за пропуск — иначе трещины."),
    Crop("wheat", "Пшеница", "пшеницы", 750.0, 9.1, 21.3, 1.6, 14.0, 19.0, 6.0, 6.0, 140.0, 50.0, 60.0,
         "Озимая и яровая. Перегрев портит клейковину: нагрев зерна до 50 °C, сильной и семенной — ниже."),
    Crop("rapeseed", "Рапс", "рапса", 650.0, 4.4, 16.0, 1.0, 8.0, 12.0, 6.0, 6.0, 80.0, 45.0, 60.0,
         "Озимый и яровой. Мелкие семена плохо продуваются и легко пересыхают; цель 7–8 %."),
    Crop("sunflower", "Подсолнечник", "подсолнечника", 350.0, 4.5, 13.5, 1.0, 7.0, 13.0, 6.0, 6.0, 115.0, 55.0, 60.0,
         "Пожароопасен: лузга и пух горят — чистите сушилку каждый день. Вдвое легче зерновых; цель 7 %."),
    Crop("soy", "Соя", "сои", 720.0, 5.0, 21.9, 1.0, 12.0, 17.0, 3.0, 3.0, 60.0, 30.0, 50.0,
         "Растрескивается: съём не больше 3 п.п. за проход, нагрев зерна до 30 °C, агент до 60 °C."),
)
BY_KEY: Dict[str, Crop] = {c.key: c for c in CROPS}

START_SIGMA = 0.25      # относительная ошибка скорости сушки стартовой модели культуры (оценка, не калибровка)


def get(key: Optional[str]) -> Crop:
    return BY_KEY.get(key or DEFAULT, BY_KEY[DEFAULT])


def to_crop(c: Crop, w_corn: float) -> float:
    """Влажность кукурузы → влажность культуры с той же равновесной влажностью воздуха."""
    return c.eqv8 + (w_corn - 8.0) * (c.eqv22 - c.eqv8) / 14.0


def _scale_table(table: Optional[List[List[float]]], k: float) -> Optional[List[List[float]]]:
    return [[float(d), round(float(q) * k, 3)] for d, q in table] if table else None


def start_params(crop: Crop, corn: Optional[mdl.DryerParams] = None) -> mdl.DryerParams:
    """Стартовая модель культуры: модель этой сушилки на кукурузе (corn; None — стартовая программы), пересчитанная
    по правилам из описания модуля. Для кукурузы — сама corn (или стартовая)."""
    base = corn or mdl.DryerParams()
    if crop.key == DEFAULT:
        return base
    kd = crop.density / BY_KEY[DEFAULT].density
    info = (f"стартовая: оценка для {crop.gen} по модели сушилки на кукурузе (равная равновесная влажность воздуха"
            + (f", скорость ×{crop.k_speed:g} по нормам".replace(".", ",") if crop.k_speed != 1.0 else "")
            + "), ±30 % — уточнится калибровкой по журналу")
    return replace(
        base, crop=crop.key, w_store=crop.w_store, eqv8=crop.eqv8, eqv22=crop.eqv22,
        q100=round(base.q100 * kd, 2), q_table=_scale_table(base.q_table, kd), m_dryer=round(base.m_dryer * kd, 1),
        w_eq=round(to_crop(crop, base.w_eq), 1), w_ref=round(to_crop(crop, base.w_ref), 1),
        r_ref=base.r_ref * crop.k_speed, eta=base.eta * crop.k_speed,
        out_bias=0.0, out_kw=0.0, out_kt=0.0, model_kind="empirical",
        t_agent_max=crop.t_agent_max, t_grain_max=crop.t_grain_max,
        calibrated=True, calib_info=info, phys_info=info,
        rate_sigma=START_SIGMA, rate_sigma_info=f"стартовая оценка для {crop.gen}: ±{START_SIGMA * 100:.0f} %",
        rate_scale=1.0, unc_feats=None, unc_cov=None, unc_lev=0.0, explored=None)


def ui_defaults(crop: Crop) -> Dict[str, Dict]:
    """Стартовые значения полей ввода для культуры (ключи — как в сохранённом состоянии разделов)."""
    return {
        "ui": {"w0": crop.w0, "wk": crop.w_store, "tproc": crop.t_proc, "soft": crop.soft, "hard": crop.hard},
        "ui_simple": {"w0": crop.w0, "wk": crop.w_store, "lim": crop.soft},
        "ui_live": {"wk": crop.w_store, "w_target": round(max(crop.w0 - crop.soft, crop.w_store), 1)},
        "ui_weekend": {"w0": crop.w0, "wk": crop.w_store},
    }
